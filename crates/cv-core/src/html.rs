#[cfg(test)]
mod tests {
    use super::*;
    use crate::ir::{Block, GitInfo, Harness, Message, Role, Session, Usage};

    fn sample_session() -> Session {
        let mut user = Message::new(Role::User);
        user.content.push(Block::Text {
            text: "Hello & welcome. Try <script>alert(1)</script> please.\n\nSecond para with `inline` code.".into(),
        });

        let mut assistant = Message::new(Role::Assistant);
        assistant.content.push(Block::Thinking {
            text: "I should be careful with <html>.".into(),
            signature: None,
            encrypted: None,
            redacted: false,
        });
        assistant.content.push(Block::Text {
            text: "Sure! Here is code:\n\n```rust\nfn main() { println!(\"<hi>\"); }\n```".into(),
        });
        assistant.content.push(Block::ToolUse {
            id: "t1".into(),
            name: "Bash".into(),
            input: serde_json::json!({ "command": "echo <x> & done" }),
        });
        assistant.usage = Some(Usage {
            input_tokens: Some(42),
            output_tokens: Some(7),
            cache_read_tokens: None,
            cache_creation_tokens: None,
        });

        let mut tool = Message::new(Role::Tool);
        tool.content.push(Block::ToolResult {
            tool_use_id: "t1".into(),
            content: "stdout: <x> & done".into(),
            is_error: true,
            tool_name: Some("Bash".into()),
            status: Some("error".into()),
            details: None,
        });
        tool.content.push(Block::File {
            mime: None,
            path: Some("/tmp/<weird>&.txt".into()),
            source: None,
        });
        tool.content.push(Block::Image {
            media_type: Some("image/png".into()),
            data_ref: None,
        });

        let mut system = Message::new(Role::System);
        system.content.push(Block::Text {
            text: "You are a helpful assistant.".into(),
        });

        Session {
            id: "abc123".into(),
            harness: Harness::Claude,
            cwd: Some("/home/<user>/proj".into()),
            title: Some("Test & <Session>".into()),
            created_at: None,
            updated_at: None,
            model: Some("claude-opus".into()),
            git: Some(GitInfo {
                branch: Some("dev".into()),
                commit: Some("deadbeef".into()),
                remote: None,
            }),
            messages: vec![system, user, assistant, tool],
            source_path: None,
            extra: serde_json::Map::new(),
        }
    }

    #[test]
    fn escape_handles_all_specials() {
        assert_eq!(escape("a&b"), "a&amp;b");
        assert_eq!(escape("<x>"), "&lt;x&gt;");
        assert_eq!(escape("\"q\""), "&quot;q&quot;");
        assert_eq!(escape("'s'"), "&#39;s&#39;");
        assert_eq!(escape("plain"), "plain");
    }

    #[test]
    fn renders_valid_standalone_document() {
        let html = to_html(&sample_session());
        assert!(html.starts_with("<!doctype html"));
        assert!(html.contains("<html"));
        assert!(html.contains("</html>"));
        // inline CSS, no external assets/scripts
        assert!(html.contains("<style>"));
        assert!(!html.contains("<script"));
        assert!(!html.to_lowercase().contains("src=\"http"));
        assert!(html.len() > 500);
    }

    #[test]
    fn title_is_present_and_escaped() {
        let html = to_html(&sample_session());
        // The title contains & and <Session>; must appear escaped, never raw.
        assert!(html.contains("Test &amp; &lt;Session&gt;"));
        assert!(!html.contains("Test & <Session>"));
    }

    #[test]
    fn xss_payload_is_escaped() {
        let html = to_html(&sample_session());
        // The dangerous payload must be neutralized.
        assert!(html.contains("&lt;script&gt;alert(1)&lt;/script&gt;"));
        assert!(!html.contains("<script>alert"));
        // bare ampersand from user text became an entity
        assert!(html.contains("Hello &amp; welcome"));
    }

    #[test]
    fn all_roles_render() {
        let html = to_html(&sample_session());
        assert!(html.contains("msg-system"));
        assert!(html.contains("msg-user"));
        assert!(html.contains("msg-assistant"));
        assert!(html.contains("msg-tool"));
    }

    #[test]
    fn block_kinds_render() {
        let html = to_html(&sample_session());
        // thinking -> collapsible details
        assert!(html.contains("<details class=\"thinking\""));
        assert!(html.contains("🧠 reasoning"));
        // tool_use -> labeled block with tool name + json
        assert!(html.contains("tool-use"));
        assert!(html.contains("🔧 tool:"));
        assert!(html.contains("Bash"));
        // tool input json is escaped
        assert!(html.contains("echo &lt;x&gt; &amp; done"));
        // tool_result -> error marked + status
        assert!(html.contains("tool-result error"));
        assert!(html.contains("error"));
        // file + image placeholders
        assert!(html.contains("📎 file:"));
        assert!(html.contains("/tmp/&lt;weird&gt;&amp;.txt"));
        assert!(html.contains("[image]"));
        // fenced code block rendered as pre/code
        assert!(html.contains("<pre><code>"));
        assert!(html.contains("println!(&quot;&lt;hi&gt;&quot;)"));
        // inline code
        assert!(html.contains("<code>inline</code>"));
    }

    #[test]
    fn header_and_usage_render() {
        let html = to_html(&sample_session());
        // harness badge
        assert!(html.contains("class=\"badge\""));
        assert!(html.contains("claude"));
        // meta rows
        assert!(html.contains("abc123"));
        assert!(html.contains("claude-opus"));
        assert!(html.contains("dev")); // git branch
        // usage tokens
        assert!(html.contains("tokens:"));
        assert!(html.contains("in 42"));
        assert!(html.contains("out 7"));
        // footer
        assert!(html.contains("generated by"));
        assert!(html.contains("claurdvoyant"));
    }
}
