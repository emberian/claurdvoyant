//! Render a [`Session`] to a self-contained, shareable HTML page.
//!
//! The output is a single `<!doctype html>` document with all CSS inlined and **no** external
//! assets or JavaScript: it opens offline by double-click, supports light/dark via
//! `prefers-color-scheme`, and is readable on mobile. Every session-derived string is
//! HTML-escaped (see [`escape`]) so a transcript containing `<script>` etc. can never inject
//! markup into the page.

use crate::ir::{Block, Message, Role, Session, Usage};

/// Render `session` as a single self-contained HTML document (inline CSS, no external assets).
pub fn to_html(session: &Session) -> String {
    let mut out = String::new();
    out.push_str("<!doctype html>\n<html lang=\"en\">\n<head>\n");
    out.push_str("<meta charset=\"utf-8\">\n");
    out.push_str("<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n");

    let label = session.label();
    out.push_str("<title>");
    out.push_str(&escape(&label));
    out.push_str("</title>\n");

    out.push_str("<style>\n");
    out.push_str(CSS);
    out.push_str("</style>\n</head>\n<body>\n");

    render_header(session, &label, &mut out);

    out.push_str("<main>\n");
    for m in &session.messages {
        render_message(m, &mut out);
    }
    out.push_str("</main>\n");

    out.push_str(
        "<footer>generated by <strong>claurdvoyant</strong></footer>\n</body>\n</html>\n",
    );
    out
}

fn render_header(session: &Session, label: &str, out: &mut String) {
    out.push_str("<header>\n");
    out.push_str("<h1>");
    out.push_str(&escape(label));
    out.push_str("</h1>\n");

    // Harness badge, color-coded by harness.
    let h = session.harness;
    out.push_str("<div class=\"badges\">");
    out.push_str(&format!(
        "<span class=\"badge\" style=\"background:{}\">{}</span>",
        harness_color(h.as_str()),
        escape(h.as_str()),
    ));
    out.push_str("</div>\n");

    out.push_str("<dl class=\"meta\">\n");
    meta_row(out, "id", &session.id);
    if let Some(cwd) = &session.cwd {
        meta_row(out, "cwd", &cwd.display().to_string());
    }
    if let Some(model) = &session.model {
        meta_row(out, "model", model);
    }
    if let Some(git) = &session.git {
        if let Some(branch) = &git.branch {
            meta_row(out, "branch", branch);
        }
        if let Some(commit) = &git.commit {
            meta_row(out, "commit", commit);
        }
    }
    if let Some(t) = &session.created_at {
        meta_row(out, "created", &t.to_rfc3339());
    }
    if let Some(t) = &session.updated_at {
        meta_row(out, "updated", &t.to_rfc3339());
    }
    meta_row(out, "messages", &session.messages.len().to_string());
    out.push_str("</dl>\n</header>\n");
}

fn meta_row(out: &mut String, key: &str, value: &str) {
    out.push_str("<dt>");
    out.push_str(&escape(key));
    out.push_str("</dt><dd>");
    out.push_str(&escape(value));
    out.push_str("</dd>\n");
}

fn render_message(m: &Message, out: &mut String) {
    let role = role_class(m.role);
    out.push_str(&format!("<section class=\"msg msg-{role}\">\n"));

    out.push_str("<div class=\"msg-head\"><span class=\"role\">");
    out.push_str(&escape(role));
    out.push_str("</span>");
    if let Some(t) = &m.timestamp {
        out.push_str("<span class=\"ts\">");
        out.push_str(&escape(&t.to_rfc3339()));
        out.push_str("</span>");
    }
    out.push_str("</div>\n");

    out.push_str("<div class=\"msg-body\">\n");
    for b in &m.content {
        render_block(b, out);
    }
    out.push_str("</div>\n");

    if let Some(u) = &m.usage {
        render_usage(u, out);
    }

    out.push_str("</section>\n");
}

fn render_block(b: &Block, out: &mut String) {
    match b {
        Block::Text { text } => {
            out.push_str("<div class=\"text\">");
            render_text(text, out);
            out.push_str("</div>\n");
        }
        Block::Thinking { text, redacted, .. } => {
            out.push_str("<details class=\"thinking\"><summary>🧠 reasoning");
            if *redacted {
                out.push_str(" <em>(redacted)</em>");
            }
            out.push_str("</summary>\n");
            if *redacted && text.trim().is_empty() {
                out.push_str("<p class=\"redacted\">[redacted by provider]</p>");
            } else {
                out.push_str("<div class=\"text\">");
                render_text(text, out);
                out.push_str("</div>");
            }
            out.push_str("\n</details>\n");
        }
        Block::ToolUse { name, input, .. } => {
            out.push_str("<div class=\"tool tool-use\">");
            out.push_str("<div class=\"tool-label\">🔧 tool: <code>");
            out.push_str(&escape(name));
            out.push_str("</code></div>");
            let pretty = serde_json::to_string_pretty(input)
                .unwrap_or_else(|_| input.to_string());
            out.push_str("<pre><code>");
            out.push_str(&escape(&pretty));
            out.push_str("</code></pre>");
            out.push_str("</div>\n");
        }
        Block::ToolResult {
            content,
            is_error,
            tool_name,
            status,
            ..
        } => {
            let cls = if *is_error {
                "tool tool-result error"
            } else {
                "tool tool-result"
            };
            out.push_str(&format!("<div class=\"{cls}\">"));
            out.push_str("<div class=\"tool-label\">↩ result");
            if *is_error {
                out.push_str(" <span class=\"err-tag\">error</span>");
            }
            if let Some(name) = tool_name {
                out.push_str(" <code>");
                out.push_str(&escape(name));
                out.push_str("</code>");
            }
            if let Some(s) = status {
                out.push_str(" <span class=\"status\">");
                out.push_str(&escape(s));
                out.push_str("</span>");
            }
            out.push_str("</div>");
            out.push_str("<pre><code>");
            out.push_str(&escape(content));
            out.push_str("</code></pre>");
            out.push_str("</div>\n");
        }
        Block::File { path, source, .. } => {
            let label = path.as_deref().or(source.as_deref()).unwrap_or("?");
            out.push_str("<div class=\"attach\">📎 file: <code>");
            out.push_str(&escape(label));
            out.push_str("</code></div>\n");
        }
        Block::Image { media_type, .. } => {
            out.push_str("<div class=\"attach\">🖼 [image]");
            if let Some(mt) = media_type {
                out.push_str(" <code>");
                out.push_str(&escape(mt));
                out.push_str("</code>");
            }
            out.push_str("</div>\n");
        }
    }
}

fn render_usage(u: &Usage, out: &mut String) {
    let mut parts: Vec<String> = Vec::new();
    if let Some(v) = u.input_tokens {
        parts.push(format!("in {v}"));
    }
    if let Some(v) = u.output_tokens {
        parts.push(format!("out {v}"));
    }
    if let Some(v) = u.cache_read_tokens {
        parts.push(format!("cache read {v}"));
    }
    if let Some(v) = u.cache_creation_tokens {
        parts.push(format!("cache write {v}"));
    }
    if parts.is_empty() {
        return;
    }
    out.push_str("<div class=\"usage\">tokens: ");
    out.push_str(&escape(&parts.join(" · ")));
    out.push_str("</div>\n");
}

/// Render plain text with minimal, *safe* markdown niceties:
/// - blank lines split paragraphs (`<p>`),
/// - single newlines become `<br>`,
/// - triple-backtick fenced blocks become `<pre><code>`,
/// - inline `` `code` `` becomes `<code>`.
///
/// All text is escaped first; we never trust session content as markup.
fn render_text(text: &str, out: &mut String) {
    // Split on fenced code blocks. A fence is a line that is exactly ``` (optionally with a lang).
    let mut in_fence = false;
    let mut fence_buf = String::new();
    let mut para_buf = String::new();

    let flush_para = |para: &mut String, out: &mut String| {
        let trimmed = para.trim_matches('\n');
        if trimmed.is_empty() {
            para.clear();
            return;
        }
        out.push_str("<p>");
        render_inline(trimmed, out);
        out.push_str("</p>\n");
        para.clear();
    };

    for line in text.split('\n') {
        let is_fence = line.trim_start().starts_with("```");
        if is_fence {
            if in_fence {
                // close fence
                out.push_str("<pre><code>");
                out.push_str(&escape(&fence_buf));
                out.push_str("</code></pre>\n");
                fence_buf.clear();
                in_fence = false;
            } else {
                // open fence — flush any pending paragraph first
                flush_para(&mut para_buf, out);
                in_fence = true;
            }
            continue;
        }
        if in_fence {
            fence_buf.push_str(line);
            fence_buf.push('\n');
            continue;
        }
        if line.trim().is_empty() {
            flush_para(&mut para_buf, out);
        } else {
            if !para_buf.is_empty() {
                para_buf.push('\n');
            }
            para_buf.push_str(line);
        }
    }
    // unterminated fence: render what we have as a code block.
    if in_fence && !fence_buf.is_empty() {
        out.push_str("<pre><code>");
        out.push_str(&escape(&fence_buf));
        out.push_str("</code></pre>\n");
    }
    flush_para(&mut para_buf, out);
}

/// Render a single paragraph's worth of text: escape everything, turn single newlines into
/// `<br>`, and wrap inline `` `code` `` spans in `<code>`.
fn render_inline(s: &str, out: &mut String) {
    let mut rest = s;
    while let Some(start) = rest.find('`') {
        // text before the backtick
        push_with_breaks(&rest[..start], out);
        let after = &rest[start + 1..];
        if let Some(end) = after.find('`') {
            out.push_str("<code>");
            out.push_str(&escape(&after[..end]));
            out.push_str("</code>");
            rest = &after[end + 1..];
        } else {
            // unmatched backtick: treat literally
            push_with_breaks(&rest[start..], out);
            return;
        }
    }
    push_with_breaks(rest, out);
}

/// Escape `s` and convert single `\n` into `<br>`.
fn push_with_breaks(s: &str, out: &mut String) {
    let mut first = true;
    for line in s.split('\n') {
        if !first {
            out.push_str("<br>\n");
        }
        first = false;
        out.push_str(&escape(line));
    }
}

/// HTML-escape the five significant characters. Hand-rolled to keep cv-core dep-light.
/// This is the single trust boundary: every session-derived string passes through here.
pub fn escape(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        match c {
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            '"' => out.push_str("&quot;"),
            '\'' => out.push_str("&#39;"),
            _ => out.push(c),
        }
    }
    out
}

fn role_class(r: Role) -> &'static str {
    match r {
        Role::System => "system",
        Role::User => "user",
        Role::Assistant => "assistant",
        Role::Tool => "tool",
    }
}

